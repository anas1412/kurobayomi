//! Generates `MsgKey` (one variant per English message id), `MsgKey::args`, and the embedded
//! locale table from `locales/`. Output goes to `OUT_DIR`.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

use fluent_syntax::ast::Entry;

#[path = "src/ftl_vars.rs"]
mod ftl_vars;

/// Keywords that need the `r#` prefix as identifiers. `self`, `Self`, `super`, `crate` and `_`
/// cannot be raw identifiers, so a message with one of those names is a build error.
const RAW_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
    "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
    "abstract", "become", "box", "do", "final", "gen", "macro", "override", "priv", "try",
    "typeof", "unsized", "virtual", "yield",
];
const NOT_RAW: &[&str] = &["crate", "self", "Self", "super", "_"];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/ftl_vars.rs");
    println!("cargo:rerun-if-changed=locales");

    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let locales = manifest.join("locales");

    let en_path = locales.join("en").join("kurobayomi.ftl");
    let en_text = fs::read_to_string(&en_path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", en_path.display()));
    let resource = match fluent_syntax::parser::parse(en_text.as_str()) {
        Ok(resource) => resource,
        Err((_, errors)) => panic!("{} does not parse: {errors:?}", en_path.display()),
    };

    let mut seen = BTreeSet::new();
    let mut messages: Vec<(String, Vec<String>)> = Vec::new();
    for entry in &resource.body {
        let Entry::Message(message) = entry else {
            continue;
        };
        let id = message.id.name.to_string();
        if !id.starts_with(|c: char| c.is_ascii_alphabetic())
            || !id.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        {
            panic!("message id {id:?} is not a Rust identifier after normalisation");
        }
        if NOT_RAW.contains(&id.as_str()) {
            panic!("message id {id:?} is a Rust keyword that cannot be raw");
        }
        if !seen.insert(id.clone()) {
            panic!("duplicate message id {id:?} in {}", en_path.display());
        }
        messages.push((id, ftl_vars::message_vars(message)));
    }

    let mut keys = String::new();
    keys.push_str(
        "/// One variant per message id in `locales/en/kurobayomi.ftl`. Generated by build.rs.\n",
    );
    keys.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[allow(non_camel_case_types)]\npub enum MsgKey {\n");
    for (id, _) in &messages {
        let name = variant_name(id);
        writeln!(keys, "    {name},").unwrap();
    }
    keys.push_str("}\n\n");
    writeln!(
        keys,
        "/// Number of message keys.\npub const MSG_COUNT: usize = {};\n",
        messages.len()
    )
    .unwrap();
    keys.push_str("impl MsgKey {\n");
    keys.push_str("    /// Every key, in English file order.\n");
    keys.push_str("    pub const ALL: &'static [MsgKey] = &[\n");
    for (id, _) in &messages {
        writeln!(keys, "        MsgKey::{},", variant_name(id)).unwrap();
    }
    keys.push_str("    ];\n\n");
    keys.push_str("    /// The Fluent message id.\n    pub const fn id(self) -> &'static str {\n        match self {\n");
    for (id, _) in &messages {
        writeln!(keys, "            MsgKey::{} => {id:?},", variant_name(id)).unwrap();
    }
    keys.push_str("        }\n    }\n\n");
    keys.push_str(
        "    /// Variables the English message reads (`argN`, and `count` for plurals).\n",
    );
    keys.push_str(
        "    pub const fn args(self) -> &'static [&'static str] {\n        match self {\n",
    );
    for (id, vars) in &messages {
        let list: Vec<String> = vars.iter().map(|v| format!("{v:?}")).collect();
        writeln!(
            keys,
            "            MsgKey::{} => &[{}],",
            variant_name(id),
            list.join(", ")
        )
        .unwrap();
    }
    keys.push_str("        }\n    }\n\n");
    keys.push_str(
        "    /// The key for a Fluent id (for example a spec file's `title`), or `None` if the English\n",
    );
    keys.push_str("    /// file has no such message.\n");
    keys.push_str("    pub fn from_id(id: &str) -> Option<MsgKey> {\n        match id {\n");
    for (id, _) in &messages {
        writeln!(
            keys,
            "            {id:?} => Some(MsgKey::{}),",
            variant_name(id)
        )
        .unwrap();
    }
    keys.push_str("            _ => None,\n        }\n    }\n}\n");
    fs::write(out_dir.join("keys.rs"), keys).expect("writing keys.rs");

    let mut table = String::from(
        "/// Embedded `locales/<tag>/kurobayomi.ftl` files, in tag order. Generated by build.rs.\n",
    );
    table.push_str("pub static LOCALE_SOURCES: &[(&str, &str)] = &[\n");
    let mut dirs: Vec<PathBuf> = fs::read_dir(&locales)
        .expect("reading locales/")
        .map(|e| e.expect("locales entry").path())
        .filter(|p| p.join("kurobayomi.ftl").is_file())
        .collect();
    dirs.sort();
    for dir in dirs {
        let tag = dir
            .file_name()
            .and_then(|n| n.to_str())
            .expect("utf-8 locale dir")
            .to_string();
        if !tag.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
            panic!("locale directory {tag:?} is not a BCP 47 tag");
        }
        let file = dir.join("kurobayomi.ftl");
        writeln!(
            table,
            "    ({tag:?}, include_str!({:?})),",
            file.display().to_string()
        )
        .unwrap();
    }
    table.push_str("];\n");
    fs::write(out_dir.join("locales.rs"), table).expect("writing locales.rs");
}

/// `r#` for keywords, otherwise the id unchanged.
fn variant_name(id: &str) -> String {
    if RAW_KEYWORDS.contains(&id) {
        format!("r#{id}")
    } else {
        id.to_string()
    }
}
