#!/usr/bin/env python3
"""Generates src/theme/schemes.rs (the Default colour scheme) from the Aniyomi colour XML resources.

Usage: python3 gen_schemes.py [ANIYOMI_SRC] [OUT_FILE]
Output is deterministic: running it twice gives byte-identical files.
"""
import os
import re
import sys

ANIYOMI = sys.argv[1] if len(sys.argv) > 1 else "/home/blackbox/aniyomi-src"
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "schemes.rs")

PC = "presentation-core/src/main/res"
APP = "app/src/main/res"

# (Rust variant name, day file, resource root) for the one scheme the app uses. The other palettes were cut.
SCHEMES = [
    ("Default", "values/colors_tachiyomi.xml", PC),
]

# Role order must match src/theme/tokens.rs `Role` (index = discriminant).
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground", "surface", "onSurface", "surfaceVariant",
    "onSurfaceVariant", "surfaceTint", "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim", "surfaceBright", "surfaceDim",
    "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "surfaceContainerLow", "surfaceContainerLowest",
    # The two aliases (tokens.rs `Role::PrimaryInverseAlias`, `Role::ElevationOverlay`).
    "primaryInverse", "elevationOverlay",
]
assert len(ROLES) == 38

COLOR_RE = re.compile(r'<color name="([A-Za-z]+)_([A-Za-z]+)">([^<]*)</color>')


def read_file(rel_root, rel_file, night):
    base = os.path.join(ANIYOMI, rel_root, rel_file)
    if night:
        base = base.replace("values/", "values-night/", 1)
    with open(base, encoding="utf-8") as f:
        return f.read()


def parse(text):
    """Returns {token: value} with @color references resolved inside the same file."""
    raw = {}
    for m in COLOR_RE.finditer(text):
        raw[m.group(2)] = (m.group(1), m.group(3).strip())
    out = {}
    for tok, (prefix, val) in raw.items():
        if val.startswith("@color/"):
            ref = val[len("@color/"):]
            target = ref.split("_", 1)[1] if "_" in ref else ref
            val = raw.get(target, (None, None))[1]
        if val and re.fullmatch(r"#[0-9A-Fa-f]{6}|#[0-9A-Fa-f]{8}", val):
            digits = val[1:]
            if len(digits) == 6:
                digits = "FF" + digits
            out[tok] = digits.upper()
    return out


def rust_opt(v):
    return "None" if v is None else "Some(Rgba::argb(0x%s))" % v


def build_table(rel_root, rel_file):
    day = parse(read_file(rel_root, rel_file, False))
    night = parse(read_file(rel_root, rel_file, True))
    return day, night


def main():
    name, rel_file, rel_root = SCHEMES[0]
    day, night = build_table(rel_root, rel_file)
    lines = []
    lines.append("//! The default colour scheme, generated from the Aniyomi XML resources.")
    lines.append("//!")
    lines.append("//! GENERATED by `src/theme/gen/gen_schemes.py`. Do not edit by hand.")
    lines.append("//! Omitted roles are `None` and resolve to the baseline (see `baseline.rs`).")
    lines.append("")
    lines.append("use super::tokens::Rgba;")
    lines.append("")
    lines.append("/// One scheme, light and dark tables indexed by `Role as usize`.")
    lines.append("pub struct SchemeDef {")
    lines.append("    pub name: &'static str,")
    lines.append("    pub light: [Option<Rgba>; 38],")
    lines.append("    pub dark: [Option<Rgba>; 38],")
    lines.append("}")
    lines.append("")
    lines.append("pub const DEFAULT_SCHEME: SchemeDef = SchemeDef {")
    lines.append('    name: "%s",' % name)
    for mode, table in (("light", day), ("dark", night)):
        lines.append("    %s: [" % mode)
        for role in ROLES:
            # Generated constants keep the role name as a comment for review.
            lines.append("        %s, // %s" % (rust_opt(table.get(role)), role))
        lines.append("    ],")
    lines.append("};")
    lines.append("")
    text = "\n".join(lines)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
